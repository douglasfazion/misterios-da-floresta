import {readFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {resolve} from 'node:path';
import assert from 'node:assert/strict';
const root=resolve(import.meta.dirname,'..');
const source=await readFile(root+'/art-source/v0.3.9-walk-generated/joca-walk.png');
const shipped=await readFile(root+'/public/assets/joca-walk.png');
const sha=(data)=>createHash('sha256').update(data).digest('hex');
assert.equal(sha(shipped),sha(source),'The playable atlas must be byte-identical to the approved v0.3.9 walk atlas');
assert.equal(shipped.toString('hex',0,8),'89504e470d0a1a0a','PNG signature');
assert.equal(shipped.readUInt32BE(16),1536,'Atlas width');
assert.equal(shipped.readUInt32BE(20),1024,'Atlas height');
console.log(`JOCA v0.3.9: corrected walk atlas verified (1536×1024, 8 frames, SHA256 ${sha(shipped).slice(0,16)}…)`);
